#!/usr/bin/env node
/**
 * Regenerates the committed word lists. Run manually, never at build or run
 * time — the game must not depend on the network or on npm metadata to start.
 *
 *   npm run words:generate --workspace @arcade/cipher
 *
 * Sources (both MIT-licensed):
 *   ALLOWED  an-array-of-english-words (SCOWL-derived) -> every real 5-letter word
 *   ANSWERS  first20hours/google-10000-english        -> common words, frequency-ordered
 *
 * ANSWERS is a strict subset of ALLOWED and is used only for the facilitator's
 * "random word" button and for ranking autocomplete. There is exactly one
 * allow list, as the spec requires.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
/** @type {string[]} ~275k words; the package ships a plain index.json. */
const englishWords = require('an-array-of-english-words');

const FIVE_LETTERS = /^[a-z]{5}$/;
const ANSWERS_URL =
  'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa.txt';

const here = dirname(fileURLToPath(import.meta.url));
const wordsDir = resolve(here, '../src/words');

function die(message) {
  console.error(`generate-wordlist: ${message}`);
  process.exit(1);
}

function emit(fileName, blobName, countName, words, description) {
  const blob = words.join('');
  const body = `// GENERATED by scripts/generate-wordlist.mjs — do not edit by hand.
// ${description}
//
// Stored as one fixed-width blob (${words.length} words x 5 chars) rather than an
// array literal: it parses faster, minifies smaller and gzips better than
// ${words.length} quoted strings. Slice it in 5-char strides to read it back.

export const ${countName} = ${words.length};

export const ${blobName} =
  '${blob}';
`;
  writeFileSync(resolve(wordsDir, fileName), body, 'utf8');
  console.log(`  ${fileName}: ${words.length} words (${(blob.length / 1024).toFixed(1)} KB)`);
}

/**
 * Read the blocklist out of blocklist.ts by pulling its quoted literals. Keeps
 * blocklist.ts the single source of truth for both the runtime and this script
 * without adding a build step or a second copy that could drift.
 */
function readBlocklist() {
  const source = readFileSync(resolve(wordsDir, 'blocklist.ts'), 'utf8');
  const body = source.slice(source.indexOf('BLOCKED_WORDS'));
  const words = [...body.matchAll(/'([a-z]+)'/g)].map((m) => m[1]);
  if (words.length === 0) die('could not parse blocklist.ts');
  return new Set(words);
}

async function main() {
  const blocked = readBlocklist();

  const allowed = [...new Set(englishWords.filter((w) => FIVE_LETTERS.test(w)))]
    .filter((w) => !blocked.has(w))
    .sort();
  if (allowed.length < 5000) die(`allow list suspiciously small (${allowed.length})`);

  const allowedSet = new Set(allowed);

  const res = await fetch(ANSWERS_URL);
  if (!res.ok) die(`fetching answers: HTTP ${res.status}`);
  const text = await res.text();

  const seen = new Set();
  const answers = [];
  for (const raw of text.split('\n')) {
    const word = raw.trim();
    // Frequency order is preserved: index 0 is the most common word.
    if (!FIVE_LETTERS.test(word)) continue;
    if (!allowedSet.has(word) || seen.has(word)) continue;
    seen.add(word);
    answers.push(word);
  }
  if (answers.length < 500) die(`answer pool suspiciously small (${answers.length})`);

  // Invariants the runtime and tests rely on. Fail loudly rather than commit junk.
  for (const word of [...allowed, ...answers]) {
    if (!FIVE_LETTERS.test(word)) die(`bad word "${word}"`);
    if (blocked.has(word)) die(`blocked word "${word}" survived filtering`);
  }
  for (const word of answers) {
    if (!allowedSet.has(word)) die(`answer "${word}" is not in the allow list`);
  }

  console.log('generate-wordlist:');
  emit(
    'allowed.generated.ts',
    'ALLOWED_BLOB',
    'ALLOWED_COUNT',
    allowed,
    'Every allowed 5-letter word, sorted. Source: an-array-of-english-words (MIT, SCOWL-derived).',
  );
  emit(
    'answers.generated.ts',
    'ANSWER_BLOB',
    'ANSWER_COUNT',
    answers,
    'Common words for the random-word button, most frequent first. Source: google-10000-english (MIT). Strict subset of ALLOWED_BLOB.',
  );
}

await main();
